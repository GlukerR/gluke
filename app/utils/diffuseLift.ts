/*
 * Подъём уровня чёрного у диффузной карты вьювера модели.
 *
 * `diffuseLift` в контенте кейса задан в единицах канала 0–255: так его
 * задавал прежний попиксельный проход по canvas — `v + lift · (1 − v/255)`.
 * В шейдере тот же подъём — `mix(v, 1, f)` над нормированным цветом, и
 * коэффициент смешивания обязан быть долей: f = lift / 255.
 *
 * Отдельной функцией, потому что эта разница единиц уже ломала картинку:
 * в шейдер ушло сырое 30 вместо 30/255, `mix` экстраполировал цвет в 30 раз
 * за белый, и текстуры Getic и Softlogic выбило полностью.
 */
export function diffuseLiftMix(lift: number): number {
  if (!(lift > 0)) return 0
  return Math.min(1, lift / 255)
}
