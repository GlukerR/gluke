/**
 * Версия картинки в адресе варианта ipx — и где она не работает.
 *
 * Карточки, шапки и галерея грузят картинки не напрямую, а через `/_ipx/**`:
 * провайдер строит адрес как `/_ipx/<модификаторы>/<путь до файла>`. Query
 * такой адрес не принимает (проверено: `?v=…` → 403 от ipx), а версия в пути
 * ломает разрешение файла (404). Поэтому версия едет отдельным модификатором
 * `v_<отпечаток>`: `@nuxt/image` сериализует любой ключ модификаторов без
 * белого списка, а ipx незнакомый модификатор игнорирует — картинка отдаётся та
 * же, но адрес меняется вместе с содержимым исходника, и кэш браузера и CDN не
 * залипают на прежней.
 *
 * За тем, что ipx по-прежнему терпит незнакомый модификатор, следит
 * `pnpm check:cache`: он поднимает собранный сервер и запрашивает такой адрес.
 * Если ipx начнёт валидировать модификаторы, упадёт проверка, а не картинки на
 * сайте. Сама версия считается при сборке (`scripts/media-versions.mjs`), в
 * рантайме это просто карта в конфиге.
 *
 * **Чего этот модификатор не делает.** На Vercel картинки идут не через ipx, а
 * через платформенный оптимизатор `/_vercel/image?url=…&w=…&q=…`, и модификатор
 * туда не попадает вовсе: провайдер выводит только `url`, `w` и `q`. Проверено
 * на боевом домене: `/_vercel/image?…&v=deadbeef`, `…&foo=1` и даже
 * `url=…jpg%3Fv%3D…` отдают тот же кэшированный ответ — query в ключе кэша
 * Vercel не участвует. Потери здесь нет: для локальных картинок оптимизатор
 * ключует варианты по отпечатку содержимого исходника (документация Image
 * Optimization, «Local images cache key»), поэтому замена файла вместе с
 * передеплоем сама даёт новый вариант. Остаётся окно кэша браузера и края — его
 * закрывает пурж по исходной картинке: `pnpm media:purge`
 * (`scripts/purge-image-cache.mjs`). Разбор — `docs/changes-log.md` §77.
 */

/** Путь картинки без query и фрагмента: по нему ищется отпечаток. */
export function imagePath(src: string): string {
  const index = src.search(/[?#]/)

  return index === -1 ? src : src.slice(0, index)
}

/**
 * Отпечаток содержимого картинки из карты сборки.
 *
 * `undefined` — картинка версии не получила: её нет на диске, это не файл
 * проекта или расширение не картинное. Адрес тогда уходит как есть.
 */
export function lookupImageVersion(
  src: string,
  versions: Record<string, string> | undefined,
): string | undefined {
  return versions?.[imagePath(src)]
}

/**
 * Модификаторы ipx с версией картинки — или пустой объект, если версии нет.
 *
 * Разворачивается в модификаторы запроса к картинке: без версии адрес остаётся
 * прежним, с версией получает `v_<отпечаток>`.
 */
export function ipxVersionModifier(
  src: string,
  versions: Record<string, string> | undefined,
): Record<string, string> {
  const version = lookupImageVersion(src, versions)

  return version ? { v: version } : {}
}
